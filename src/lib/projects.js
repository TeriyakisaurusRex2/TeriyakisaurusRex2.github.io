// Loads the project list at build time.
//
// 1. Ask GitHub for every public repo on the account.
// 2. Keep only the ones tagged with the "teriyaki" topic (that's how you opt a repo in).
// 3. For each, read the optional teriyaki/project.json in the repo for extra details
//    (screenshots, video, status, created date...), and for Watch projects the README.
// 4. If nothing is tagged yet, or GitHub can't be reached, fall back to sample data
//    so the site still renders while you're working on it.

import sample from '../data/sample-projects.json';

export const GITHUB_USER = 'TeriyakisaurusRex2';
const TOPIC = 'teriyaki';
const API = 'https://api.github.com';

// Placeholder colours for projects that don't have a thumbnail yet.
// Picked from the project name, so each project keeps the same colour between builds.
const TINTS = ['#3B4A6B', '#2E5E4E', '#6A3FA0', '#A88A4A', '#5B2A4E', '#2F7D6D', '#C24A3A', '#4A5D23', '#B8577A', '#1F2933'];

function headers(accept = 'application/vnd.github+json') {
  const h = { Accept: accept, 'User-Agent': 'teriyaki-projects' };
  // On GitHub Actions a token is provided automatically; it raises the API limit
  // from 60 to 1000+ requests an hour. Locally it's optional.
  if (process.env.GITHUB_TOKEN) h.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  return h;
}

// Fetch that returns null instead of throwing (used for files that may not exist).
async function fetchOptional(url, accept) {
  try {
    const res = await fetch(url, { headers: headers(accept) });
    if (!res.ok) return null;
    return accept?.includes('html') ? await res.text() : await res.json();
  } catch {
    return null;
  }
}

// "fret-path" -> "Fret Path"
function prettify(repoName) {
  return repoName.replace(/[-_]+/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());
}

function hash(text) {
  let h = 0;
  for (const ch of text) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return h;
}

// YouTube links become embeds; anything ending in a video extension plays in <video>.
function mediaKind(item) {
  if (!item.src) return 'placeholder';
  if (/youtube\.com|youtu\.be/.test(item.src)) return 'youtube';
  if (/\.(mp4|webm|mov)$/i.test(item.src)) return 'video';
  return 'image';
}

function youtubeId(url) {
  const m = url.match(/(?:v=|youtu\.be\/|embed\/)([\w-]{11})/);
  return m ? m[1] : null;
}

// Fills in everything the pages need, whether the project came from GitHub or the sample file.
function normalize(p) {
  const media = (p.media ?? []).map((m) => {
    const kind = mediaKind(m);
    const ytId = kind === 'youtube' ? youtubeId(m.src) : null;
    // A placeholder can still be marked as a video (sample data) so it gets a play icon.
    const isMotion = kind === 'video' || kind === 'youtube' || m.kind === 'video';
    return { ...m, kind, ytId, isMotion };
  });
  return {
    ...p,
    media,
    // Playable projects live at their own GitHub Pages address (teriyakiprojects.io/<repo>/),
    // unless project.json points somewhere else (e.g. Noporogue on Netlify).
    // Watch projects get a page generated by this site at the same kind of address.
    url: p.playUrl ?? `/${p.slug}/`,
    isExternal: Boolean(p.playUrl),
    initials: p.name.split(/\s+/).map((w) => w[0]).join('').slice(0, 2).toUpperCase(),
    tint: p.color ?? TINTS[hash(p.name) % TINTS.length],
  };
}

async function fromRepo(repo) {
  const raw = (path) =>
    `https://raw.githubusercontent.com/${GITHUB_USER}/${repo.name}/${repo.default_branch}/${path}`;
  // Paths in project.json are relative to the repo's teriyaki/ folder; full URLs pass through.
  const asset = (path) => (!path ? null : /^https?:\/\//.test(path) ? path : raw(`teriyaki/${path.replace(/^\.?\//, '')}`));

  const info = (await fetchOptional(raw('teriyaki/project.json'))) ?? {};
  // If you don't say, a repo with GitHub Pages turned on counts as playable.
  const type = info.type ?? (repo.has_pages ? 'play' : 'watch');
  // GitHub renders the README to HTML for us (same look as on github.com, minus styling).
  const readmeHtml =
    type === 'watch'
      ? await fetchOptional(`${API}/repos/${GITHUB_USER}/${repo.name}/readme`, 'application/vnd.github.html+json')
      : null;

  return normalize({
    slug: repo.name,
    name: info.name ?? prettify(repo.name),
    description: info.description ?? repo.description ?? '',
    about: info.about ?? null,
    tags: info.tags ?? (repo.topics ?? []).filter((t) => t !== TOPIC),
    language: info.language ?? repo.language ?? '',
    type,
    category: info.category ?? 'game',
    engine: info.engine ?? '',
    status: info.status ?? '',
    // GitHub's creation date is when the repo was made, which may be long after the project
    // started, so project.json can override it.
    created: info.created ?? repo.created_at,
    updated: repo.pushed_at,
    playUrl: info.playUrl ?? null,
    thumbnail: asset(info.thumbnail),
    color: info.color,
    media: (info.media ?? []).map((m) => ({ ...m, src: asset(m.src) })),
    repoUrl: repo.html_url,
    readmeHtml,
    isSample: false,
  });
}

async function load() {
  try {
    const res = await fetch(`${API}/users/${GITHUB_USER}/repos?per_page=100`, { headers: headers() });
    if (!res.ok) throw new Error(`GitHub answered ${res.status}`);
    const repos = await res.json();
    const tagged = repos.filter((r) => !r.fork && (r.topics ?? []).includes(TOPIC));
    if (tagged.length > 0) return await Promise.all(tagged.map(fromRepo));
    console.warn(`[teriyaki] No repos tagged "${TOPIC}" yet, showing sample data.`);
  } catch (err) {
    console.warn(`[teriyaki] Couldn't reach GitHub (${err.message}), showing sample data.`);
  }
  return sample.map((p) =>
    normalize({ ...p, repoUrl: `https://github.com/${GITHUB_USER}/${p.slug}`, readmeHtml: null, isSample: true })
  );
}

// Every page asks for the projects; this makes sure GitHub is only asked once per build.
let cached;
export function getProjects() {
  cached ??= load();
  return cached;
}
